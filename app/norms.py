def describe_observation(e, zone_src, rule_state=None) -> str:
    """Observed vs unverified wording for one observation (pipeline event dict)."""
    o = e
    zone_txt = (f"предполагаемое рабочее место — область наибольшей плотности детекций ({zone_src}); "
                "роль человека в этой зоне видео не устанавливает")
    if e["type"] == "operator_zone_unattended_with_counter_activity":
        txt = (f"Наблюдаемо: {o['start_sec']:.1f}–{o['end_sec']:.1f} с (~{o['duration_sec']:.0f} с) детектор не "
               f"находит человека в зоне ({zone_txt}; в остальное время зона занята в "
               f"{o['zone_occupancy_elsewhere']:.0%} проверок); движение рядом с зоной {o['activity_motion']:.2%} "
               f"пикселей, другой человек в кадре в {o['other_person_ratio']:.0%} проверок. "
               "Не проверено: кто находился в зоне и какова его роль, действительно ли человек покинул место "
               "(детектор может пропускать людей при виде сверху/перекрытии), шло ли или завершилось "
               "обслуживание клиента. ")
    else:
        txt = (f"Наблюдаемо: {o['start_sec']:.1f}–{o['end_sec']:.1f} с (~{o['duration_sec']:.0f} с) в зоне "
               f"({zone_txt}) одновременно два и более человека ({o['two_persons_ratio']:.0%} проверок). "
               "Не проверено: роль и полномочия людей (присутствие контролёра может быть обязательным), "
               "цель присутствия. ")
    txt += f"Уверенность (эвристика, не калибрована): {e['confidence']:.2f}. "
    if rule_state and not rule_state["validated"]:
        txt += ("Правило НЕ валидировано (демо-режим ALLOW_UNVALIDATED_RULES=1): качество не измерено, "
                "вывод не может считаться установленным нарушением. ")
    return txt
